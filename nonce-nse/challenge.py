def _hmac_sha256(key: bytes, msg: bytes) -> bytes:
    if len(key) > 64:
        key = hashlib.sha256(key).digest()
    key = key.ljust(64, b"\x00")
    o = bytes(b ^ 0x5C for b in key)
    i = bytes(b ^ 0x36 for b in key)
    return hashlib.sha256(o + hashlib.sha256(i + msg).digest()).digest()


def hkdf_sha256(ikm: bytes, salt: bytes, info: bytes, length: int = 32) -> bytes:
    if salt == b"":
        salt = b"\x00" * 32
    prk = _hmac_sha256(salt, ikm)
    okm, t, c = b"", b"", 1
    while len(okm) < length:
        t = _hmac_sha256(prk, t + info + bytes([c]))
        okm += t
        c += 1
    return okm[:length]


def derive_key(d: int) -> bytes:
    ikm = hashlib.sha256(DOMAIN + int(d).to_bytes(32, "big")).digest()
    return hkdf_sha256(ikm, KDF_SALT, KDF_INFO, 32)


def seal_flag(d: int, flag: bytes) -> dict:
    key = derive_key(d)
    cipher = AES.new(key, AES.MODE_GCM)
    ct, tag = cipher.encrypt_and_digest(flag)
    return {
        "cipher": "AES-256-GCM",
        "nonce": cipher.nonce.hex(),
        "ciphertext": ct.hex(),
        "tag": tag.hex(),
    }
